/** Snapshot-backed identities, shared by web and native. No region flags. */
export const currencyIcons: readonly CurrencyIconMetadata[] = iso4217Units
  .filter((unit) => unit.kind === 'currency')
  .map((unit) => ({
    code: unit.code,
    name: unit.name,
    glyph: glyphs[unit.code] ?? '¤',
    kind: 'currency',
    foreground: '#FFFFFF',
    background: '#1F3151',
  }));
const byCode = new Map(currencyIcons.map((icon) => [icon.code, icon]));

/** Ledger commodities are case-sensitive. Never trim or uppercase into a match. */
export function getCurrencyIcon(commodity: string): CurrencyIconMetadata {
  return (
    byCode.get(commodity) ?? {
      code: commodity,
      name: commodity,
      glyph: '◇',
      kind: 'custom',
      foreground: '#5B6775',
      background: '#F2F4F7',
    }
  );
}
